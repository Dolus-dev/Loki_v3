import { PermissionFlagsBits, SlashCommandBuilder } from 'discord.js';
import { Logger } from '../../../framework/logger.js';
import { defineCommand } from '../../../framework/types.js';
import { CreateModerationEventInput } from '../../lib/backend.js';

/**
 * /generate-moderation-events: generates a bunch of moderation events for testing purposes. Only works in dev servers.
 *
 * RELATED TODO: Update framework to skip this command in production builds, so this command can't be accidentally used in production.
 *
 * This is a dev-only command that generates a bunch of moderation events for testing purposes. It can be used to test the bot's handling of moderation events, such as lifting temporary bans/mutes/timeouts as they expire.
 */

export default defineCommand({
  devOnly: true,

  data: new SlashCommandBuilder()
    .setName('generate-moderation-events')
    .setDescription('Generates a bunch of moderation events for testing purposes. Only works in dev servers.')
    .addIntegerOption((option) =>
      option
        .setName('count')
        .setDescription('The number of moderation events to generate.')
        .setRequired(false)
        .setMinValue(1),
    )
    .addStringOption((option) =>
      option
        .setName('type')
        .setDescription('The type of moderation event to generate.')
        .setRequired(true)
        .setChoices(
          { name: 'ban', value: 'ban' },
          { name: 'mute', value: 'mute' },
          { name: 'timeout', value: 'timeout' },
          { name: 'kick', value: 'kick' },
          { name: 'warn', value: 'warn' },
          { name: 'note', value: 'note' },
          { name: 'random', value: 'random' },
        ),
    )
    // To be updated to the autcomplete system from the regular commands.
    .addIntegerOption((option) =>
      option
        .setName('max-duration')
        .setDescription('The maximum duration for a temporary moderation event (in seconds).')
        .setRequired(false)
        .setMinValue(1),
    )
    // Hidden from non-admins by default; server settings can grant it to specific people instead
    .setDefaultMemberPermissions(PermissionFlagsBits.Administrator),

  async execute(interaction) {
    const options = interaction.options;

    const [count, type] = [options.getInteger('count') ?? 50, options.getString('type', true)];
    const maxDuration = options.getInteger('max-duration') ?? 3600;

    // TODO: Implement the command logic to generate moderation events

    if (type === 'random') {
      let eventCount: number = 0;
      const generatedEventsCount = new Map<string, number>();
      const generatedEvents = new Map<string, number>();
      generatedEventsCount.set('ban', 0);
      generatedEventsCount.set('mute', 0);
      generatedEventsCount.set('timeout', 0);
      generatedEventsCount.set('kick', 0);
      generatedEventsCount.set('warn', 0);
      generatedEventsCount.set('note', 0);
      const eventTypes = ['ban', 'mute', 'timeout', 'kick', 'warn', 'note'];

      do {
        const selectedType = eventTypes[Math.floor(Math.random() * eventTypes.length)]!;
        generatedEvents.set(selectedType, generatedEvents.get(selectedType)! + 1);

        const event: CreateModerationEventInput = {
          issuedBy: interaction.user.id,
          eventType: selectedType as 'ban' | 'mute' | 'warn' | 'timeout' | 'kick' | 'note',
          reason: `Test ${selectedType} event generated by /generate-moderation-events command.`,
          // Add a random duration for temporary events
          expiresAt:
            selectedType === 'ban' || selectedType === 'mute' || selectedType === 'timeout'
              ? new Date(Date.now() + Math.floor(Math.random() * maxDuration) * 1000).toISOString()
              : undefined,
        };
      } while (eventCount < count);
    }
  },
});
